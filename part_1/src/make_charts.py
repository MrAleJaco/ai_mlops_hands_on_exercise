"""Charts for the Census Income dataset.

The figures follow part_1/data/designs/Charts.jpg:

    CHARTS
    |- DISTRIBUTION .................. box plots (shows outliers)
    |     |- CATEGORICAL COLS ........ box plot of the category counts
    |     '- NUMERICAL COLS .......... box plot of the values
    |- RELATION WITH TARGET (INCOME)
    |     |- NUMERICAL COLS .......... box plot per column, target 0 / 1
    |     '- CATEGORICAL COLS ........ grouped bar chart of the target
    |                                   percentage inside each category
    '- RELATION BETWEEN VARIABLES
          |- NUM COLS ................ scatterplot
          '- CATEGORICAL COLS ........ N/A in the design, skipped on purpose

Usage (from the repository root):

    uv run python part_1/src/make_charts.py

    uv run python part_1/src/make_charts.py \
        --input part_1/data/raw_data/census_income.csv \
        --out-dir part_1/data/processed/figures
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # render to files only: no window, works in Docker/CI

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

from census_pipeline import CATEGORICAL_COLS, NUMERIC_COLS, TARGET, load_analysis_frame

# ---------------------------------------------------------------------------
# STEP 1 - One visual language for every figure
# Why:     the same colour must mean the same class everywhere, so a reader
#          learns the palette once. These two blues/reds stay distinguishable
#          for the most common colour-vision deficiencies.
# ---------------------------------------------------------------------------
TARGET_LABELS = {0: "<=50K", 1: ">50K"}
TARGET_PALETTE = {"<=50K": "#2E6F9E", ">50K": "#C0392B"}
NEUTRAL = {"numeric": "#2E6F9E", "categorical": "#2E8B57"}
REFERENCE_COLOR = "#C0392B"
DPI = 150

PART_DIR = Path(__file__).resolve().parents[1]  # .../part_1
DEFAULT_INPUT = PART_DIR / "data" / "raw_data" / "census_income.csv"
DEFAULT_OUT_DIR = PART_DIR / "data" / "processed" / "figures"

sns.set_theme(style="whitegrid", context="notebook")
plt.rcParams.update(
    {
        "figure.titlesize": 15,
        "axes.titlesize": 10.5,
        "axes.labelsize": 9.5,
        "xtick.labelsize": 8.5,
        "ytick.labelsize": 8.5,
        "axes.edgecolor": "#888888",
        "figure.facecolor": "white",
    }
)


# ---------------------------------------------------------------------------
# STEP 2 - Small helpers shared by the figures
# Why:     outlier counting, saving and the "source" footnote are repeated in
#          every figure; writing them once keeps the chart code readable.
# ---------------------------------------------------------------------------
def outlier_count(values: pd.Series) -> tuple[int, float]:
    """Count values outside 1.5 x IQR, the same rule a box plot draws with."""
    clean = values.dropna()
    q1, q3 = clean.quantile([0.25, 0.75])
    iqr = q3 - q1
    count = int(((clean < q1 - 1.5 * iqr) | (clean > q3 + 1.5 * iqr)).sum())
    return count, 100 * count / len(clean)


def save(fig: plt.Figure, path: Path, subject: str, rows: int) -> None:
    """Write the PNG and close it, so figures cannot pile up in memory."""
    fig.text(
        0.01,
        -0.02,
        f"Source: {subject} - {rows:,} rows - generated by part_1/src/make_charts.py",
        fontsize=7.5,
        color="#666666",
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=DPI, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"  written {path}")


# ---------------------------------------------------------------------------
# STEP 3 - DISTRIBUTION: box plots, the designed way to expose outliers
# Why:     one panel per column keeps every column on its own scale, which
#          matters here because fnlwgt is in the 100,000s while age is in the
#          10s. For categorical columns the box holds the *category counts*,
#          so a rare level shows up as an outlier - exactly what the design
#          asks the box plots to reveal.
# ---------------------------------------------------------------------------
def plot_distribution(df: pd.DataFrame, path: Path, subject: str) -> str:
    fig = plt.figure(figsize=(16, 13))
    fig.suptitle(
        "Distribution of every column - box plots expose the outliers",
        fontweight="bold",
    )
    numeric_panel, categorical_panel = fig.subfigures(2, 1, height_ratios=[6, 7])

    # --- Numerical columns: one box each -------------------------------
    numeric_panel.suptitle("Numerical columns (one box per column)", fontsize=11)
    numeric_axes = numeric_panel.subplots(2, 3)
    numeric_panel.subplots_adjust(hspace=0.55, wspace=0.30, top=0.86)

    for ax, col in zip(numeric_axes.ravel(), NUMERIC_COLS):
        values = df[col].dropna()
        count, share = outlier_count(values)

        sns.boxplot(
            y=values,
            ax=ax,
            width=0.35,
            color=NEUTRAL["numeric"],
            flierprops={
                "marker": "o",
                "markersize": 2.5,
                "alpha": 0.35,
                "markeredgewidth": 0,
            },
        )
        ax.set_title(col)
        ax.set_ylabel("")
        ax.text(
            0.02,
            0.98,
            f"{count:,} outliers ({share:.1f}%)\nmax {values.max():,.0f}",
            transform=ax.transAxes,
            va="top",
            fontsize=7.5,
            color="#444444",
            bbox={"boxstyle": "round,pad=0.3", "facecolor": "white", "edgecolor": "#DDDDDD"},
        )

    # --- Categorical columns: one box of category counts each ----------
    categorical_panel.suptitle(
        "Categorical columns - each dot is the number of rows in one category",
        fontsize=11,
    )
    categorical_axes = categorical_panel.subplots(2, 4).ravel()
    categorical_panel.subplots_adjust(hspace=0.60, wspace=0.35, top=0.86)

    rarest_column = None
    for ax, col in zip(categorical_axes, CATEGORICAL_COLS):
        counts = df[col].value_counts()
        rarest = counts.idxmin()

        sns.boxplot(
            y=counts.values,
            ax=ax,
            width=0.35,
            color=NEUTRAL["categorical"],
            flierprops={
                "marker": "o",
                "markersize": 3,
                "alpha": 0.6,
                "markeredgewidth": 0,
            },
        )
        ax.set_title(f"{col}\n{len(counts)} levels, rarest: {rarest} (n={counts.min():,})")

        # Very uneven columns (native-country is 43,782 vs 1) would be a flat
        # line on a linear axis, hiding exactly the rare levels we look for.
        if counts.max() / counts.min() >= 100:
            ax.set_yscale("log")
            ax.set_ylabel("rows in category (log)")
        else:
            ax.set_ylabel("rows in category")

        if rarest_column is None or counts.min() < rarest_column[1]:
            rarest_column = (f"{col} / {rarest}", int(counts.min()))

    for ax in categorical_axes[len(CATEGORICAL_COLS):]:
        ax.set_visible(False)

    save(fig, path, subject, len(df))

    zero_gain = 100 * (df["capital-gain"] == 0).mean()
    zero_loss = 100 * (df["capital-loss"] == 0).mean()
    return (
        f"{zero_gain:.1f}% of capital-gain and {zero_loss:.1f}% of capital-loss rows are zero, "
        f"so those two columns are mostly a single spike; the rarest categorical level is "
        f"{rarest_column[0]} with only {rarest_column[1]:,} row(s)."
    )


# ---------------------------------------------------------------------------
# STEP 4 - RELATION WITH TARGET, numerical side
# Why:     the design asks for "box plot for every num col, target 0 or 1".
#          One panel per column answers one question: does the distribution
#          move between the two income classes, and by how much?
# ---------------------------------------------------------------------------
def plot_target_vs_numeric(df: pd.DataFrame, path: Path, subject: str) -> str:
    data = df.assign(income_label=df[TARGET].map(TARGET_LABELS))

    fig, axes = plt.subplots(2, 3, figsize=(15, 8), constrained_layout=True)
    fig.suptitle(
        "Every numerical column, split by income class",
        fontweight="bold",
    )

    for ax, col in zip(axes.ravel(), NUMERIC_COLS):
        sns.boxplot(
            data=data,
            x="income_label",
            y=col,
            hue="income_label",
            order=list(TARGET_PALETTE),
            hue_order=list(TARGET_PALETTE),
            palette=TARGET_PALETTE,
            legend=False,
            width=0.5,
            ax=ax,
            flierprops={
                "marker": "o",
                "markersize": 2,
                "alpha": 0.25,
                "markeredgewidth": 0,
            },
        )
        medians = data.groupby("income_label")[col].median()
        means = data.groupby("income_label")[col].mean()
        ax.set_title(
            f"{col}\nmedian {medians['<=50K']:,.0f} vs {medians['>50K']:,.0f} | "
            f"mean {means['<=50K']:,.0f} vs {means['>50K']:,.0f}",
            fontsize=9.5,
        )
        ax.set_xlabel("")
        ax.set_ylabel("")

    save(fig, path, subject, len(df))

    medians = data.groupby("income_label")[NUMERIC_COLS].median()
    low, high = medians.loc["<=50K"], medians.loc[">50K"]
    comparable = low[(low > 0) & (high > 0)].index
    relative = (high[comparable] - low[comparable]) / low[comparable]
    biggest = relative.idxmax()
    return (
        f"{biggest} shows the largest relative median shift "
        f"({low[biggest]:,.0f} -> {high[biggest]:,.0f}, {relative[biggest] * 100:+.0f}%), "
        f"then age ({low['age']:,.0f} -> {high['age']:,.0f}, {relative['age'] * 100:+.0f}%); "
        f"fnlwgt moves only {relative['fnlwgt'] * 100:+.1f}%, so the sampling weight "
        "is not a behavioural signal. capital-gain/loss keep a median of 0 in both "
        "classes, but their means differ, so the tail - not the typical row - is the signal."
    )


# ---------------------------------------------------------------------------
# STEP 5 - RELATION WITH TARGET, categorical side
# Why:     the design asks for a grouped bar chart per categorical column,
#          showing the target percentage inside each category. Here the group
#          is the column and each bar is one category, so a reader can see
#          which levels concentrate high earners.
# Gotcha:  a category with n=1 has a share of 0% or 100% and means nothing.
#          The n label next to every bar makes that obvious.
# ---------------------------------------------------------------------------
def _target_share_bars(
    ax: plt.Axes, df: pd.DataFrame, col: str, overall: float, label_size: float
) -> None:
    """Draw horizontal bars of P(income >50K) for one categorical column."""
    stats = (
        df.groupby(col, observed=True)[TARGET]
        .agg(share="mean", n="size")
        .sort_values("share", ascending=True)
    )
    positions = np.arange(len(stats))
    shares = stats["share"].to_numpy() * 100

    ax.barh(positions, shares, height=0.72, color=NEUTRAL["numeric"])
    ax.axvline(
        overall * 100,
        color=REFERENCE_COLOR,
        linestyle="--",
        linewidth=1,
        label=f"overall {overall * 100:.1f}%",
    )

    for y, (share, n) in enumerate(zip(shares, stats["n"])):
        ax.text(
            share + 0.8,
            y,
            f"{share:.0f}% (n={n:,})",
            va="center",
            fontsize=label_size,
            color="#333333",
        )

    ax.set_yticks(positions, stats.index, fontsize=label_size + 1)
    ax.set_xlim(0, max(shares.max() * 1.30, overall * 100 * 1.5))
    ax.set_xlabel("share of the category earning >50K (%)")
    ax.set_title(f"{col} ({len(stats)} categories)", loc="left")
    ax.legend(loc="lower right", fontsize=label_size + 0.5, frameon=True)


def plot_target_vs_categorical(df: pd.DataFrame, path: Path, subject: str) -> str:
    small_columns = [col for col in CATEGORICAL_COLS if df[col].nunique() <= 15]
    wide_columns = [col for col in CATEGORICAL_COLS if col not in small_columns]
    overall = df[TARGET].mean()

    fig = plt.figure(figsize=(17, 22))
    fig.suptitle(
        "Share of people earning >50K inside every category of every categorical column",
        fontweight="bold",
    )
    top, bottom = fig.subfigures(2, 1, height_ratios=[3, 1.6])

    axes = top.subplots(3, 2).ravel()
    top.subplots_adjust(hspace=0.55, wspace=0.45, top=0.93)
    for ax, col in zip(axes, small_columns):
        _target_share_bars(ax, df, col, overall, label_size=7)
    for ax in axes[len(small_columns):]:
        ax.set_visible(False)

    bottom.suptitle(
        "High-cardinality column (many categories, so it gets its own panel)",
        fontsize=11,
    )
    wide_axes = bottom.subplots(len(wide_columns), 1, squeeze=False).ravel()
    bottom.subplots_adjust(hspace=0.5, top=0.90)
    for ax, col in zip(wide_axes, wide_columns):
        _target_share_bars(ax, df, col, overall, label_size=6)

    save(fig, path, subject, len(df))

    by_marital = (
        df.groupby("marital-status")[TARGET].agg(["mean", "size"]).sort_values("mean")
    )
    top_row = by_marital.iloc[-1]
    bottom_row = by_marital.iloc[0]
    return (
        f"marital-status separates the classes most: {by_marital.index[-1]} reaches "
        f"{top_row['mean'] * 100:.1f}% high earners (n={top_row['size']:,.0f}) against "
        f"{bottom_row['mean'] * 100:.1f}% for {by_marital.index[0]} "
        f"(overall {overall * 100:.1f}%)."
    )


# ---------------------------------------------------------------------------
# STEP 6 - RELATION BETWEEN VARIABLES, numerical side
# Why:     a scatterplot matrix shows every pair of numeric columns at once,
#          which is how you spot the disguised duplicates, the hard caps
#          (capital-gain max 99,999) and the pairs that separate the classes.
# Gotcha:  ~49k points per panel is heavy, so points are semi-transparent and
#          rasterised; the PNG stays small and the file opens fast.
#          Categorical x categorical is N/A in the design and is not drawn.
# ---------------------------------------------------------------------------
def plot_relation_numeric(df: pd.DataFrame, path: Path, subject: str) -> str:
    data = df.assign(income_label=df[TARGET].map(TARGET_LABELS))
    columns = NUMERIC_COLS
    size = len(columns)

    # A hand-built lower triangle instead of sns.pairplot: full control over
    # the layout, one shared axis per row/column, and no empty upper triangle.
    fig, axes = plt.subplots(
        size,
        size,
        figsize=(14, 13),
        sharex="col",  # a column always holds the same variable on the x axis
        constrained_layout=True,
    )

    for row_index, row_name in enumerate(columns):
        for col_index, col_name in enumerate(columns):
            ax = axes[row_index, col_index]

            # Upper triangle: nothing to draw there.
            if col_index > row_index:
                ax.set_visible(False)
                continue

            for value, label in TARGET_LABELS.items():
                colour = TARGET_PALETTE[label]
                subset = data[data[TARGET] == value]

                if row_index == col_index:
                    # Diagonal: density, so the two classes are comparable
                    # even though one has three times more rows.
                    ax.hist(
                        subset[col_name].dropna(),
                        bins=30,
                        density=True,
                        alpha=0.55,
                        color=colour,
                        label=label,
                    )
                else:
                    ax.scatter(
                        subset[col_name],
                        subset[row_name],
                        s=4,
                        alpha=0.18,
                        color=colour,
                        linewidths=0,
                        rasterized=True,
                    )

            if row_index == size - 1:
                ax.set_xlabel(col_name)
            if col_index == 0:
                ax.set_ylabel(row_name)
            else:
                # Every row shows one variable on the y axis; repeat the label
                # only once, on the left, to keep the matrix readable.
                ax.tick_params(labelleft=False)
            if row_index == col_index:
                ax.set_ylabel("density")

    handles = [
        plt.Line2D([], [], marker="o", linestyle="", color=TARGET_PALETTE[label], label=label)
        for label in TARGET_PALETTE
    ]
    fig.legend(handles=handles, title="income", loc="upper right", frameon=True)
    fig.suptitle(
        "Relation between the numerical columns, coloured by income class",
        fontweight="bold",
    )
    save(fig, path, subject, len(df))

    return (
        "Age and education-num are the only columns whose clouds separate the two income "
        "classes cleanly; capital-gain sits on a hard cap at 99,999 and capital-loss on "
        "round bands, which are artefacts of how the variable was recorded, not behaviour."
    )


# ---------------------------------------------------------------------------
# STEP 7 - Command line entry point
# Why:     one command rebuilds every figure from the raw file, which is what
#          "runs from a fresh clone" means for the report.
# ---------------------------------------------------------------------------
def parse_args() -> argparse.Namespace:
    """Read the input file and output folder from the command line."""
    parser = argparse.ArgumentParser(description="Render the EDA figures.")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT, help="Raw CSV.")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR, help="Folder for PNGs.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    df = load_analysis_frame(args.input)
    subject = args.input.name

    print(f"Chart source : {args.input}")
    print(f"Rows         : {len(df):,}")
    print(f"Output folder: {args.out_dir}\n")

    captions = [
        ("01_distribution.png", plot_distribution),
        ("02_target_vs_numeric.png", plot_target_vs_numeric),
        ("03_target_vs_categorical.png", plot_target_vs_categorical),
        ("04_relation_numeric.png", plot_relation_numeric),
    ]

    print("Rendering figures...")
    claims = []
    for filename, plotter in captions:
        claims.append((filename, plotter(df, args.out_dir / filename, subject)))

    print("\nRelation between categorical columns: N/A in the design - skipped.")
    print("\nCaptions:")
    for filename, claim in claims:
        print(f"  {filename}: {claim}")

    print(f"\n{len(claims)} figures written to {args.out_dir}")


if __name__ == "__main__":
    main()
